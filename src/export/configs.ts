// The apps that have no setting for letter spacing
const NO_LETTER_SPACING: Record<string, string> = {
    emacs: 'Emacs has',
    putty: 'PuTTY has',
    sublimeText: 'Sublime Text has',
    intellij: 'JetBrains IDEs have',
};

/** A warning for the instructions when the export cannot apply all of the settings. */
function exportWarning(editor: string, settings: Settings): string | undefined {
    const spacing = settings.letterSpacing || 0;
    if (spacing) {
        if (NO_LETTER_SPACING[editor]) {
            return `${NO_LETTER_SPACING[editor]} no setting for letter spacing. Your letter spacing of ${spacing}px is not in the export.`;
        }
        if (editor === 'vim') {
            const columnSpace = Math.round(spacing);
            return `Only MacVim has a setting for letter spacing (<code>columnspace</code>), and it takes whole pixels. `
                + (columnSpace
                    ? `The export sets it to ${columnSpace} for MacVim. Other versions of Vim show the font without your letter spacing of ${spacing}px.`
                    : `Your letter spacing of ${spacing}px rounds to 0, so it is not in the export.`);
        }
        if (editor === 'gnomeTerminal' && spacing < 0) {
            return `GNOME Terminal can only make the letter spacing wider. Your letter spacing of ${spacing}px is not in the export.`;
        }
    }
    if (editor === 'iterm2' && !postscriptName(settings)) {
        return `iTerm2 identifies a font by its PostScript name, and we do not know that name for ${primaryFontName(settings.font)}. `
            + `The export has a guess (<code>${guessedPostscriptName(settings)}</code>). If the profile shows another font, select the font on the <strong>Text</strong> tab of the profile.`;
    }
    return undefined;
}

function saveBlob(blob: Blob, filename: string): void {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

// Download the configuration for one editor. An editor that needs several files gets a ZIP file.
export async function downloadConfig(editor: string): Promise<void> {
    const template = configTemplates[editor];
    if (!template) return;

    fontNames = (await import('../../font-names.json')).default as Record<string, FontNames>;
    const settings = currentSettings();
    const files = template(settings);
    if (files.length === 1) {
        saveBlob(new Blob([files[0].content], { type: 'text/plain' }), files[0].filename);
    } else {
        const { default: JSZip } = await import('jszip');
        const zip = new JSZip();
        files.forEach(file => zip.file(file.filename, file.content));
        saveBlob(await zip.generateAsync({ type: 'blob' }), `phoropter-${editor.toLowerCase()}.zip`);
    }

    // Show installation instructions after download
    showInstallationInstructions(editor, exportWarning(editor, settings));
}


function showInstallationInstructions(editor: string, warning?: string): void {
    const instructions = installationInstructions[editor];
    if (!instructions) return;
    
    // Create modal overlay
    const modal = document.createElement('div');
    modal.className = 'instruction-modal';
    modal.innerHTML = `
        <div class="instruction-content">
            <div class="instruction-header">
                <h3>${instructions.title}</h3>
                <button class="close-btn" data-action="closeModal">×</button>
            </div>
            <div class="instruction-body">
                ${warning ? `<p class="instruction-warning">${warning}</p>` : ''}
                <ol>
                    ${instructions.steps.map(step => `<li>${step}</li>`).join('')}
                </ol>
            </div>
            <div class="instruction-footer">
                <button data-action="closeModal">Got it!</button>
            </div>
        </div>
    `;
    
    document.body.appendChild(modal);
}
